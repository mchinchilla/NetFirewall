using System.Net;
using System.Text;
using NetFirewall.Models.Network;

namespace NetFirewall.Services.Network;

/// <summary>A name to publish: a reservation's hostname or the one a client sent with its lease.</summary>
public sealed record LocalDnsHost(string RawName, IPAddress Address, bool IsReservation);

/// <summary>A DHCP subnet and the DNS domain its hosts live in (null = the default).</summary>
public sealed record LocalDnsDomain(string NetworkCidr, string? Domain);

/// <summary>
/// Renders the Unbound include that publishes DHCP hostnames — A + PTR as local-data under each
/// subnet's domain (fallback <see cref="DefaultDomain"/>) — so `ping nas.home.lan` works from any
/// LAN device. Reservations win over leases for the same name; one PTR per address; names are
/// sanitized to DNS labels (a phone's "Marvin's iPhone" → marvins-iphone). Pure, deterministic
/// (sorted) so an unchanged lease table renders a byte-identical file and nothing is reloaded.
/// </summary>
public static class LocalDnsZone
{
    public const string DefaultDomain = "lan";
    private const int Ttl = 300;

    public static string Render(IEnumerable<LocalDnsHost> hosts, IReadOnlyList<LocalDnsDomain> domains)
    {
        var parsed = domains
            .Select(d => (Cidr: ParseCidr(d.NetworkCidr), Domain: NormalizeDomain(d.Domain)))
            .Where(d => d.Cidr is not null)
            .ToList();

        var byFqdn = new Dictionary<string, IPAddress>(StringComparer.Ordinal);
        var ptr = new Dictionary<string, string>(StringComparer.Ordinal);
        // Reservations first so they win a name clash; then leases, newest data order as given.
        foreach (var h in hosts.OrderByDescending(h => h.IsReservation))
        {
            var label = h.IsReservation && DnsHostName.IsValid(h.RawName) ? h.RawName : DnsHostName.Sanitize(h.RawName);
            if (label is null) continue;
            var domain = parsed.FirstOrDefault(d => Contains(d.Cidr!.Value, h.Address)).Domain ?? DefaultDomain;
            var fqdn = $"{label}.{domain}";
            if (!byFqdn.TryAdd(fqdn, h.Address)) continue;           // name taken (by a reservation or earlier lease)
            ptr.TryAdd(h.Address.ToString(), fqdn);
        }

        var sb = new StringBuilder();
        sb.AppendLine("# Generated by NetFirewall from DHCP leases and reservations — do not edit (rewritten every 30 s).");
        sb.AppendLine("server:");
        foreach (var zone in byFqdn.Keys.Select(f => f[(f.IndexOf('.') + 1)..]).Distinct().Order(StringComparer.Ordinal))
            sb.AppendLine($"    local-zone: \"{zone}.\" transparent");
        foreach (var (fqdn, ip) in byFqdn.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            sb.AppendLine($"    local-data: \"{fqdn}. {Ttl} IN A {ip}\"");
        foreach (var (ip, fqdn) in ptr.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            sb.AppendLine($"    local-data-ptr: \"{ip} {fqdn}\"");
        return sb.ToString();
    }

    /// <summary>"home.lan" / "home.lan." → "home.lan"; anything that isn't dotted DNS labels → null.</summary>
    private static string? NormalizeDomain(string? domain)
    {
        var d = domain?.Trim().TrimEnd('.').ToLowerInvariant();
        return !string.IsNullOrEmpty(d) && d.Split('.').All(DnsHostName.IsValid) ? d : null;
    }

    private static (uint Net, uint Mask)? ParseCidr(string cidr)
    {
        var slash = cidr.IndexOf('/');
        if (slash < 0 || !IPAddress.TryParse(cidr[..slash], out var ip) || !int.TryParse(cidr[(slash + 1)..], out var len) || len is < 0 or > 32)
            return null;
        var mask = len == 0 ? 0u : uint.MaxValue << (32 - len);
        return (ToUInt(ip) & mask, mask);
    }

    private static bool Contains((uint Net, uint Mask) cidr, IPAddress ip) => (ToUInt(ip) & cidr.Mask) == cidr.Net;

    private static uint ToUInt(IPAddress ip)
    {
        Span<byte> b = stackalloc byte[4];
        return ip.TryWriteBytes(b, out var n) && n == 4 ? System.Buffers.Binary.BinaryPrimitives.ReadUInt32BigEndian(b) : 0;
    }
}
